def protected_snapshot() -> dict[str, str]:
    """Extend Stage 6H integrity hashes to all production app source files."""
    result = integrity_snapshot()
    app_files = sorted(path for path in (RAG / "app").rglob("*")
                       if path.is_file() and "__pycache__" not in path.parts)
    manifest = hashlib.sha256()
    for path in app_files:
        manifest.update(str(path.relative_to(ROOT)).encode("utf-8"))
        manifest.update(bytes.fromhex(digest(path)))
    result["rag-service/app (recursive source manifest)"] = manifest.hexdigest()
    return result


def load_data() -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Load answerable eval items and corpus chunks."""
    data = json.loads(EVAL.read_text(encoding="utf-8-sig"))
    chunks = json.loads(CHUNKS.read_text(encoding="utf-8-sig"))["chunks"]
    return [x for x in data["items"] if not x["should_abstain"]], chunks


def query_for_variant(query: str, terms: list[str]) -> str:
    return " ".join([query, *terms])


def conservative_terms(query: str, all_terms: list[str], vocab: set[str]) -> list[str]:
    """Keep only suffix-removal variants already generated by the Stage 6H rule."""
    allowed: list[str] = []
    for term in dict.fromkeys(tokens(query)):
        direct = []
        if len(term) > 4 and term.endswith("ies"):
            direct.append(term[:-3] + "y")
        elif len(term) > 3 and term.endswith("s") and not term.endswith("ss"):
            direct.append(term[:-1])
        for candidate in direct:
            if candidate in vocab and candidate in all_terms and candidate not in allowed:
                allowed.append(candidate)
    return allowed[:5]


def results_for(retriever: LegalRetriever, item: dict[str, Any], query: str) -> list[dict[str, Any]]:
    jurisdiction = item["jurisdiction"] if item["jurisdiction"] in {"India", "International"} else "all"
    return retriever.retrieve(query, top_k=10, jurisdiction=jurisdiction)


def target_ranks(results: list[dict[str, Any]], targets: list[dict[str, Any]]) -> list[int | None]:
    return [next((rank for rank, row in enumerate(results, 1) if matches_target(row, target)), None)
            for target in targets]


def status(rank: int | None, cutoff: int) -> str:
    return "Y" if rank is not None and rank <= cutoff else "N"


def target_state(old: int | None, new: int | None) -> str:
    if (old is None or old > 10) and new is not None and new <= 10:
        return "newly recovered"
    if old is not None and old <= 10 and (new is None or new > 10):
        return "newly lost"
    if old is None and new is None:
        return "unchanged"
    if old is None or new is None:
        return "degraded" if new is None else "improved"
    if new < old:
        return "improved"
    if new > old:
        return "degraded"
    return "unchanged"


def metrics(items: list[dict[str, Any]], ranks: dict[str, list[int | None]]) -> dict[str, Any]:
    return _metric_record(items, ranks)


def fmt(value: Any) -> str:
    return "—" if value is None else str(value)


def result_label(row: dict[str, Any]) -> str:
    return f"{row.get('document_name')} {row.get('provision_type') or ''} {row.get('provision_number') or ''}".strip()


def type_bucket(item: dict[str, Any]) -> str:
    if item["category"] == "explicit_provisions":
        return "Explicit provision"
    if item["category"] == "comparisons":
        return "Comparison"
    if item["category"] == "definitions" or item["intent"] == "definition":
        return "Definition"
    if item["category"] == "patentability":
        return "Patentability"
    if item["category"] == "patent_procedure":
        return "Procedure"
    return "General"


def analyze() -> tuple[str, dict[str, Any]]:
    items, chunks = load_data()
    corpus = build_corpus_stats(chunks)
    vocab = set(corpus["provision_df"])
    retriever = LegalRetriever()
    variant_names = ("Baseline", "Current morphology", "Conservative morphology")
    outputs: dict[str, dict[str, list[dict[str, Any]]]] = {name: {} for name in variant_names}
    terms_by_query: dict[str, list[str]] = {}
    expanded_by_query: dict[str, str] = {}
    for item in items:
        expanded, _, added, _ = make_expansions(item["query"], corpus)
        conservative = conservative_terms(item["query"], added, vocab)
        terms_by_query[item["id"]] = added
        expanded_by_query[item["id"]] = expanded
        outputs["Baseline"][item["id"]] = results_for(retriever, item, item["query"])
        outputs["Current morphology"][item["id"]] = results_for(retriever, item, expanded)
        outputs["Conservative morphology"][item["id"]] = results_for(
            retriever, item, query_for_variant(item["query"], conservative))

    ranks: dict[str, dict[str, list[int | None]]] = {
        variant: {item["id"]: target_ranks(outputs[variant][item["id"]], item["expected_targets"])
                  for item in items} for variant in variant_names}
    overall = {variant: metrics(items, ranks[variant]) for variant in variant_names}
    categories: dict[str, dict[str, Any]] = {}
    for category, label in CATEGORY_LABELS.items():
        selected = [item for item in items if item["category"] == category]
        if selected:
            categories[label] = {variant: metrics(selected, {x["id"]: ranks[variant][x["id"]]
                                                              for x in selected}) for variant in variant_names}

    target_records: list[dict[str, Any]] = []
    for item in items:
        for i, target in enumerate(item["expected_targets"]):
            old, new, cons = (ranks[name][item["id"]][i] for name in variant_names)
            target_records.append({"item": item, "target": target, "old": old, "new": new, "cons": cons,
                                  "state": target_state(old, new)})

    term_effects: dict[str, dict[str, Any]] = {}
    for item in items:
        old_ranks = ranks["Baseline"][item["id"]]
        new_ranks = ranks["Current morphology"][item["id"]]
        moved_better = any((o is None or o > 10) and n is not None and n <= 10 or
                           (o is not None and n is not None and n < o) for o, n in zip(old_ranks, new_ranks))
        moved_worse = any((o is not None and o <= 10 and (n is None or n > 10)) or
                          (o is not None and n is not None and n > o) for o, n in zip(old_ranks, new_ranks))
        for term in terms_by_query[item["id"]]:
            row = term_effects.setdefault(term, {"queries": 0, "improved": 0, "degraded": 0, "neutral": 0})
            row["queries"] += 1
            if moved_better:
                row["improved"] += 1
            if moved_worse:
                row["degraded"] += 1
            if not moved_better and not moved_worse:
                row["neutral"] += 1

    lines = ["# Stage 6I Morphology Ablation Analysis", "",
             "## 1. Executive summary", "",
             f"Analyzed **{len(items)} answerable queries** and **{sum(len(x['expected_targets']) for x in items)} expected targets**. The main morphology arm reuses Stage 6H's existing corpus-attested suffix variant function and five-term cap. No target metadata or target text participates in expansion generation.", "",
             "## 2. Baseline reproduction", "",
             "The current Stage 6D retriever was evaluated unchanged before this analysis. Its reproduced metrics appear in the table below.", "",
             "## 3. Morphology reproduction and 4. Overall metric comparison", "",
             "| Variant | R@1 | R@3 | R@5 | R@10 | MRR |", "|---|---:|---:|---:|---:|---:|"]
    for name in variant_names:
        m = overall[name]
        lines.append(f"| {name} | {m['recall@1']:.4f} | {m['recall@3']:.4f} | {m['recall@5']:.4f} | {m['recall@10']:.4f} | {m['mrr']:.4f} |")
    lines += ["", "Expected baseline: 0.3857 / 0.5952 / 0.7381 / 0.8810 / 0.5711. Expected Stage 6H morphology: 0.4429 / 0.6524 / 0.7952 / 0.9238 / 0.6121. Any discrepancy is visible above and must be investigated; this report does not silently substitute the earlier values.", "",
              "## 5. Category-level comparison", "",
              "Metrics are macro averages using the evaluator's target-fraction Recall and earliest-target MRR convention. Delta columns are morphology or conservative minus baseline.", "",
              "| Category | Variant | R@1 (Δ) | R@3 (Δ) | R@5 (Δ) | R@10 (Δ) | MRR (Δ) |", "|---|---|---:|---:|---:|---:|---:|"]
    for category, variants in categories.items():
        base = variants["Baseline"]
        for variant in variant_names:
            m = variants[variant]
            vals = []
            for key in ("recall@1", "recall@3", "recall@5", "recall@10", "mrr"):
                delta = m[key] - base[key]
                vals.append(f"{m[key]:.4f} ({delta:+.4f})")
            lines.append(f"| {category} | {variant} | " + " | ".join(vals) + " |")
    helped, neutral, mixed = [], [], []
    for category, variants in categories.items():
        base, changed = variants["Baseline"], variants["Current morphology"]
        deltas = [changed[k] - base[k] for k in ("recall@1", "recall@3", "recall@5", "recall@10", "mrr")]
        if all(abs(delta) < 1e-12 for delta in deltas):
            neutral.append(category)
        elif sum(delta > 0 for delta in deltas) >= 3 and not any(delta < 0 for delta in deltas):
            helped.append(category)
        else:
            mixed.append(category)
    lines += ["", "### Category interpretation", "",
              f"- Clear overall gains across several metrics without a metric regression: {', '.join(helped) or 'none'}.",
              f"- Neutral across all reported metrics: {', '.join(neutral) or 'none'}.",
              f"- Mixed or concerning tradeoffs: {', '.join(mixed) or 'none'}. A single metric change is not treated as a categorical win/loss."]

    lines += ["", "## 6. Query-by-query rank changes", "",
              "Ranks refer to the target's first matching result within Top-10. Status columns state whether each target is within that cutoff.", "",
              "| ID | Category | Jurisdiction | Intent | Original query | Expanded query | Added terms (n) | Expected targets | Baseline ranks | Morphology ranks |", "|---|---|---|---|---|---|---:|---|---|---|"]
    for item in items:
        added = terms_by_query[item["id"]]
        targets = [f"{x.get('document_name')} {x.get('provision_type')} {x.get('provision_number')}" for x in item["expected_targets"]]
        old = ranks["Baseline"][item["id"]]
        new = ranks["Current morphology"][item["id"]]
        lines.append("| " + " | ".join((item["id"], item["category"], item["jurisdiction"],
            analyze_legal_query(item["query"])["intent"], item["query"].replace("|", "\\|"),
            expanded_by_query[item["id"]].replace("|", "\\|"), f"{', '.join(added) or '—'} ({len(added)})",
            "; ".join(targets), ", ".join(fmt(x) for x in old), ", ".join(fmt(x) for x in new))) + " |")

    lines += ["", "### Per-target ranks, deltas, cutoff status, and classification", "",
              "Rank delta is morphology rank minus baseline rank when both are present. A negative value is an upward rank movement. Newly recovered/lost refers to entering/leaving Top-10.", "",
              "| ID | Target | Baseline | Morphology | Δ rank | Baseline @1/@3/@5/@10 | Morph @1/@3/@5/@10 | State |", "|---|---|---:|---:|---:|---|---|---|"]
    for rec in target_records:
        target = rec["target"]
        delta = rec["new"] - rec["old"] if rec["new"] is not None and rec["old"] is not None else None
        old_status = "/".join(status(rec["old"], cutoff) for cutoff in CUTOFFS)
        new_status = "/".join(status(rec["new"], cutoff) for cutoff in CUTOFFS)
        lines.append(f"| {rec['item']['id']} | {target.get('document_name')} {target.get('provision_type')} {target.get('provision_number')} | {fmt(rec['old'])} | {fmt(rec['new'])} | {fmt(delta)} | {old_status} | {new_status} | {rec['state']} |")

    regressions = [x for x in target_records if x["state"] in {"degraded", "newly lost"}]
    recovered = [x for x in target_records if x["state"] == "newly recovered"]
    lines += ["", "## 7. Newly recovered targets", ""]
    if not recovered:
        lines.append("No expected target newly entered Top-10.")
    for rec in recovered:
        item = rec["item"]
        baseline_top = outputs["Baseline"][item["id"]][:5]
        morph_top = outputs["Current morphology"][item["id"]][:5]
        prior_ids = {row.get("chunk_id") for row in baseline_top}
        new_competitors = [result_label(row) for row in morph_top if row.get("chunk_id") not in prior_ids]
        lines.append(f"### {item['id']} — {result_label(rec['target'])}")
        lines.append(f"- Query: {item['query']}")
        lines.append(f"- Baseline rank {fmt(rec['old'])}; morphology rank {fmt(rec['new'])}; state: newly recovered.")
        lines.append(f"- Added terms: {', '.join(terms_by_query[item['id']]) or 'none'}.")
        lines.append(f"- New Top-5 competitors: {', '.join(new_competitors) or 'none'}.")
        lines.append("- Interpretation: newly present in Top-10 after expansion; observed ranking association, not proof that a specific term caused recovery.")
    lines += ["", "## 8. Newly lost/degraded targets", "",
              "For each target, new Top-5 rows absent from baseline Top-5 are listed as observed competitors. This documents ranking changes; it does not establish semantic causation.", ""]
    if not regressions:
        lines.append("No target was degraded or newly lost.")
    for rec in regressions:
        item = rec["item"]
        base_top = outputs["Baseline"][item["id"]][:5]
        morph_top = outputs["Current morphology"][item["id"]][:5]
        base_ids = {r.get("chunk_id") for r in base_top}
        competitors = [result_label(r) for r in morph_top if r.get("chunk_id") not in base_ids]
        lines.append(f"### {item['id']} — {result_label(rec['target'])}")
        lines.append(f"- Query: {item['query']}")
        lines.append(f"- Baseline rank {fmt(rec['old'])}; morphology rank {fmt(rec['new'])}; state: {rec['state']}.")
        lines.append(f"- Added terms: {', '.join(terms_by_query[item['id']]) or 'none'}.")
        lines.append(f"- New Top-5 competitors: {', '.join(competitors) or 'none'}.")
        lines.append("- Interpretation: observed displacement after the query changed; the rank evidence alone does not isolate which added term or establish semantic cause.")

    lines += ["", "## 9. Expansion-term analysis", "",
              "Term-level query outcome counts can overlap if a multi-target query has both upward and downward target movements. They are associations, not causal attribution.", "",
              "| Added term | Queries added | Queries with improved target | Degraded target | No observable target-rank effect |", "|---|---:|---:|---:|---:|"]
    for term, row in sorted(term_effects.items(), key=lambda kv: (-kv[1]["improved"], -kv[1]["degraded"], kv[0])):
        lines.append(f"| {term} | {row['queries']} | {row['improved']} | {row['degraded']} | {row['neutral']} |")
    lines.append("")
    useful = [term for term, row in term_effects.items() if row["queries"] >= 2 and row["improved"] == row["queries"]]
    neutral_terms = [term for term, row in term_effects.items() if row["neutral"] == row["queries"]]
    harmful = [term for term, row in term_effects.items() if row["degraded"] > 0]
    lines.append(f"- Consistently useful by this descriptive rule (added in ≥2 queries, all associated queries improved): {', '.join(sorted(useful)) or 'none'}.")
    lines.append(f"- Neutral in all observed uses: {', '.join(sorted(neutral_terms)) or 'none'}.")
    lines.append(f"- Potentially harmful/uncertain (associated with at least one degraded target): {', '.join(sorted(harmful)) or 'none'}.")
    lines.append("These labels do not establish per-term causation. No terms are removed on this basis.")

    lines += ["", "## 10. Query-type analysis", "",
              "| Query type | n | Baseline R@1/R@3/R@5/R@10/MRR | Morphology R@1/R@3/R@5/R@10/MRR |", "|---|---:|---|---|"]
    type_groups: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for item in items:
        type_groups[type_bucket(item)].append(item)
    for typ, group in sorted(type_groups.items()):
        b = metrics(group, {x["id"]: ranks["Baseline"][x["id"]] for x in group})
        m = metrics(group, {x["id"]: ranks["Current morphology"][x["id"]] for x in group})
        fmtm = lambda row: "/".join(f"{row[k]:.4f}" for k in ("recall@1", "recall@3", "recall@5", "recall@10", "mrr"))
        lines.append(f"| {typ} | {len(group)} | {fmtm(b)} | {fmtm(m)} |")

    lines += ["", "## 11. Explicit-provision safety", "",
              "| Evaluation ID | Explicit reference | Baseline rank | Morphology rank | Conservative rank |", "|---|---|---:|---:|---:|"]
    for item in items:
        if item["category"] != "explicit_provisions":
            continue
        explicit = analyze_legal_query(item["query"])["explicit_provision"]
        i = items.index(item)
        for n, target in enumerate(item["expected_targets"]):
            lines.append(f"| {item['id']} | {explicit} | {fmt(ranks['Baseline'][item['id']][n])} | {fmt(ranks['Current morphology'][item['id']][n])} | {fmt(ranks['Conservative morphology'][item['id']][n])} |")
    lines.append("All three named provisions are expected at rank 1 in the accepted baseline; the run below confirms actual ranks. This is a safety check on the existing evaluator, not a guarantee for arbitrary explicit references.")

    lines += ["", "## 12. Comparison-query analysis", "",
              "Coverage counts expected targets retrieved, while jurisdiction representation counts results in the returned top-k. Jurisdiction presence alone is not target success.", "",
              "| ID | Variant | Target coverage @5 | Target coverage @10 | Expected jurisdictions found @5 / @10 | Returned jurisdiction counts @5 / @10 |", "|---|---|---:|---:|---|---|"]
    for item in items:
        if item["category"] != "comparisons":
            continue
        for variant in variant_names:
            result_rows = outputs[variant][item["id"]]
            target_r = ranks[variant][item["id"]]
            found5 = [t for t, r in zip(item["expected_targets"], target_r) if r is not None and r <= 5]
            found10 = [t for t, r in zip(item["expected_targets"], target_r) if r is not None and r <= 10]
            juris5 = ", ".join(sorted({str(t.get("jurisdiction")) for t in found5})) or "none"
            juris10 = ", ".join(sorted({str(t.get("jurisdiction")) for t in found10})) or "none"
            counts5 = dict(Counter(r.get("jurisdiction") for r in result_rows[:5]))
            counts10 = dict(Counter(r.get("jurisdiction") for r in result_rows[:10]))
            lines.append(f"| {item['id']} | {variant} | {len(found5)}/{len(target_r)} | {len(found10)}/{len(target_r)} | {juris5} / {juris10} | {counts5} / {counts10} |")

    lines += ["", "## 13. Query-length analysis", "",
              "Length uses Stage 6H's substantive query tokenization. Groups: short 1–5, medium 6–10, long >10.", "",
              "| Length group | Queries | Baseline R@1/R@3/R@5/R@10/MRR | Morphology R@1/R@3/R@5/R@10/MRR |", "|---|---:|---|---|"]
    length_groups: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for item in items:
        count = len(tokens(item["query"]))
        group = "short" if count <= 5 else "medium" if count <= 10 else "long"
        length_groups[group].append(item)
    for group in ("short", "medium", "long"):
        selected = length_groups[group]
        if not selected:
            continue
        b = metrics(selected, {x["id"]: ranks["Baseline"][x["id"]] for x in selected})
        m = metrics(selected, {x["id"]: ranks["Current morphology"][x["id"]] for x in selected})
        fmtm = lambda row: "/".join(f"{row[k]:.4f}" for k in ("recall@1", "recall@3", "recall@5", "recall@10", "mrr"))
        lines.append(f"| {group} | {len(selected)} | {fmtm(b)} | {fmtm(m)} |")

    lines += ["", "## 14. Query-drift analysis", "",
              "Queries adding three or more terms are shown with their Top-5 documents before and after. A changed list signals retrieval drift, not necessarily irrelevance.", ""]
    drift = [item for item in items if len(terms_by_query[item["id"]]) >= 3]
    if not drift:
        lines.append("No query added three or more terms.")
    for item in drift:
        old_docs = ", ".join(result_label(x) for x in outputs["Baseline"][item["id"]][:5])
        new_docs = ", ".join(result_label(x) for x in outputs["Current morphology"][item["id"]][:5])
        old_ranks = ranks["Baseline"][item["id"]]
        new_ranks = ranks["Current morphology"][item["id"]]
        lines.append(f"- {item['id']}: `{item['query']}`; expanded `{expanded_by_query[item['id']]}`; +{len(terms_by_query[item['id']])} terms ({', '.join(terms_by_query[item['id']])}); target ranks {old_ranks} → {new_ranks}.")
        lines.append(f"  - Baseline Top-5: {old_docs}")
        lines.append(f"  - Morphology Top-5: {new_docs}")

    lines += ["", "## 15. Expansion-strength ablation", "",
              "A is no expansion. B exactly reuses the Stage 6H function (up to five corpus-attested singular/plural forms). C keeps only direct suffix-removal variants from that same function and vocabulary. D is not applicable: Stage 6H defines no stronger mode beyond its existing five-term cap, and adding rules would violate the no-redesign constraint.", "",
              "Overall and category metrics are reported in Sections 3–5; the conservative column isolates one smaller subset of existing variants without adding an expansion rule.", "",
              "| Variant vs baseline | Improved | Unchanged | Degraded | Newly recovered | Newly lost |", "|---|---:|---:|---:|---:|---:|"]
    movement: dict[str, Counter[str]] = {}
    for variant in ("Current morphology", "Conservative morphology"):
        state_counts = Counter()
        for item in items:
            for old, new in zip(ranks["Baseline"][item["id"]], ranks[variant][item["id"]]):
                state_counts[target_state(old, new)] += 1
        lines.append(f"| {variant} | {state_counts['improved']} | {state_counts['unchanged']} | {state_counts['degraded']} | {state_counts['newly recovered']} | {state_counts['newly lost']} |")
        movement[variant] = state_counts
    cons, base = overall["Conservative morphology"], overall["Baseline"]
    cons_deltas = ", ".join(f"{key} {cons[key] - base[key]:+.4f}" for key in ("recall@1", "recall@3", "recall@5", "recall@10", "mrr"))
    lines.append(f"\nConservative-arm interpretation: deltas vs baseline are {cons_deltas}. It has fewer degraded rank transitions than the full variant ({movement['Conservative morphology']['degraded']} vs {movement['Current morphology']['degraded']}), but it introduces {movement['Conservative morphology']['newly lost']} newly lost target(s). This is a possible future conditional design to study, not evidence that it is already safer.")
    lines += ["", "## 16. Holdout/generalization diagnostic", "",
              "Deterministic split by original evaluation order: odd-position answerable queries are the analysis subset; even-position queries are holdout. This is small and not statistically significant.", "",
              "| Split | n | Baseline R@1/R@3/R@5/R@10/MRR | Morphology R@1/R@3/R@5/R@10/MRR |", "|---|---:|---|---|"]
    def metric_string(group: list[dict[str, Any]], variant: str) -> str:
        m = metrics(group, {x["id"]: ranks[variant][x["id"]] for x in group})
        return "/".join(f"{m[k]:.4f}" for k in ("recall@1", "recall@3", "recall@5", "recall@10", "mrr"))
    for label, group in (("Analysis (odd order)", items[::2]), ("Holdout (even order)", items[1::2])):
        lines.append(f"| {label} | {len(group)} | {metric_string(group, 'Baseline')} | {metric_string(group, 'Current morphology')} |")

    lines += ["", "## 17. Root-cause interpretation", "",
              f"Observed target-level changes: {sum(x['state'] == 'improved' for x in target_records)} improved, {sum(x['state'] == 'unchanged' for x in target_records)} unchanged, {sum(x['state'] == 'degraded' for x in target_records)} degraded, {sum(x['state'] == 'newly recovered' for x in target_records)} newly recovered, and {sum(x['state'] == 'newly lost' for x in target_records)} newly lost. New competing rows are reported for regressions. These are rank associations: per-term counts do not prove which token caused a result to move.", "",
              "## 18. Recommendation", "",
              "Recommendation: **B. Morphology expansion is promising but requires a conservative/conditional design before production.** The overall reproduction and holdout split should be weighed alongside explicit-provision safety, category-level regressions, comparison target coverage, and term-level associations. This analysis does not authorize or implement a production change.", ""]
    return "\n".join(lines), {"items": items, "ranks": ranks, "metrics": overall,
                               "counts": {"items": len(items), "targets": len(target_records)}}


def main() -> int:
    """Run diagnostic, verify protected inputs/index count, and write only report."""
    before = protected_snapshot()
    count_before = chroma_record_count()
    report, details = analyze()
    after = protected_snapshot()
    count_after = chroma_record_count()
    if before != after or count_before != count_after:
        raise RuntimeError("Protected inputs or Chroma count changed during analysis")
    validation = [f"Integrity check: PASS; Chroma count {count_after}; protected hashes unchanged."]
    validation.extend(f"- `{name}`: `{value}`" for name, value in sorted(after.items()))
    report += "\n## Validation and unchanged-state checks\n\n" + "\n".join(validation)
    REPORT.write_text(report, encoding="utf-8")
    print(f"Report: {REPORT}")
    print(f"Answerable queries: {details['counts']['items']}; target instances: {details['counts']['targets']}")
    for variant, m in details["metrics"].items():
        print(variant, *(f"{m[k]:.4f}" for k in ("recall@1", "recall@3", "recall@5", "recall@10", "mrr")))
    print(f"Integrity: PASS; Chroma={count_after}")
    return 0


